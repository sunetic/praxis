from app.services.agent.service import AgentRunService
from app.services.agent.store import RunStore

SCENARIOS_PATH = Path(__file__).with_name("scenarios.json")
PADDING = " 诊断证据保持可追溯。" * 22
INSTRUCTIONS = "Answer only from the supplied conversation. Be concise, preserve identifiers, and say unknown when evidence is absent. Use the user's language."


def load_scenarios(path: Path = SCENARIOS_PATH) -> list[dict[str, Any]]:
    """Load and minimally validate the versioned scenario catalog."""

    payload = json.loads(path.read_text(encoding="utf-8"))
    scenarios = payload.get("scenarios")
    if payload.get("version") != 1 or not isinstance(scenarios, list) or not scenarios:
        raise ValueError("context compaction scenarios must use version=1 and be non-empty")
    for scenario in scenarios:
        required = {
            "id",
            "title",
            "turns",
            "required_memory_terms",
            "forbidden_memory_terms",
            "questions",
        }
        missing = sorted(required - set(scenario))
        if missing:
            raise ValueError(f"scenario {scenario.get('id', '<unknown>')} missing: {missing}")
    return scenarios


def score_answer(answer: str, question: dict[str, Any]) -> dict[str, Any]:
    """Score exact fact groups and obvious distractor leakage deterministically."""

    normalized = answer.casefold()
    groups = question.get("expected_groups") or []
    group_results = [any(str(term).casefold() in normalized for term in group) for group in groups]
    leaked = [
        term for term in question.get("forbidden") or [] if str(term).casefold() in normalized
    ]
    recall = sum(group_results) / len(group_results) if group_results else 1.0
    return {
        "recall": round(recall, 3),
        "expected_groups_passed": sum(group_results),
        "expected_groups_total": len(group_results),
        "distractor_leaks": leaked,
        "passed": recall == 1.0 and not leaked,
    }


def score_compaction(scenario: dict[str, Any], snapshots: list[dict], events: list[dict]) -> dict:
    """Keep the frozen summary-only checks and require actual token reduction.

    Protected originals may rescue an answer, but cannot hide a missing summary
    fact in this diagnostic. Only summaries actually submitted to the model count.
    This is an offline evaluation, never an online retry or completion decision.
    """
    by_id = {item["id"]: item for item in snapshots}
    projections = []
    for event in events:
        if event["kind"] != "context_compacted":
            continue
        payload = event["payload"]
        snapshot = by_id.get(payload.get("snapshot_id"))
        summary = snapshot["summary"] if snapshot else ""
        missing = [
            term
            for term in scenario["required_memory_terms"]
            if term.casefold() not in summary.casefold()
        ]
        forbidden = [
            term
            for term in scenario["forbidden_memory_terms"]
            if term.casefold() in summary.casefold()
        ]
        before, after = payload.get("before_tokens"), payload.get("after_tokens")
        reduced = isinstance(before, int) and isinstance(after, int) and 0 < after < before
        projections.append(
            {
                "event_seq": event["seq"],
                "snapshot_id": payload.get("snapshot_id"),
                "summary_present": bool(snapshot and summary),
                "required_missing": missing,
                "forbidden_retained": forbidden,
                "before_tokens": before,
                "after_tokens": after,
                "token_reduction_percent": round((1 - after / before) * 100, 1)
                if reduced
                else None,
                "passed": bool(snapshot and summary) and not missing and not forbidden and reduced,
            }
        )
    return {
        "scope": "submitted_summary_only",
        "projections": projections,
        "passed": bool(projections) and all(item["passed"] for item in projections),
    }


def score_scenario(questions: list[dict]) -> dict:
    """Preserve recall/relative-retention gates as well as per-question checks."""
    baseline = (
        sum(item["baseline"]["recall"] for item in questions) / len(questions) if questions else 0
    )
    compacted = (
        sum(item["compacted"]["recall"] for item in questions) / len(questions) if questions else 0
    )
    retention = compacted / baseline if baseline else 0
    return {
        "metrics": {
            "baseline_recall": round(baseline, 3),
            "compacted_recall": round(compacted, 3),
            "retention_ratio": round(retention, 3),
        },
        "passed": bool(questions)
        and compacted >= 0.9
        and retention >= 0.9
        and all(item["passed"] for item in questions),
    }


async def run_scenario(scenario: dict[str, Any], factory: ModelFactory) -> dict[str, Any]:
    history = []
    for user, assistant in scenario["turns"]:
        history.extend(
            [
                ModelRequest(parts=[UserPromptPart(user + PADDING)]),
                ModelResponse(parts=[TextPart(assistant + PADDING)]),
            ]
        )
    definition = AgentDefinition(
        name="retention-evaluation", tool_names=frozenset(), instructions=INSTRUCTIONS
    )
    results = []
    with tempfile.TemporaryDirectory(prefix="praxis-context-eval-") as directory:
        engine = create_engine(
            f"sqlite:///{directory}/runtime.db", connect_args={"check_same_thread": False}
        )
        Base.metadata.create_all(engine, tables=RUNTIME_TABLES)
        sessions = sessionmaker(engine)
        store = RunStore(sessions)
        service = AgentRunService(
            store,
            factory.get_model,
            {},
            capabilities_for_run=lambda row: frozenset(),
            model_snapshot_factory=factory.snapshot,
        )
        await service.start()
        try:
            for question in scenario["questions"]:
                # Every question starts from the same frozen history. Earlier test
                # answers must not contaminate recall for a later question.
                conversation = uuid.uuid4().hex
                store.create_conversation(conversation, "eval")
                seed = store.submit(
                    conversation, "eval", "fixture", scenario["turns"][0][0], definition
                )
                store.claim(seed["id"], "fixture")
                store.finish(
                    seed["id"],
                    "fixture",
                    status="finished",
                    history=history,
                    budget=ExecutionBudget(),
                    output="Frozen evaluation transcript",
                )
                baseline = await model_request(
                    await factory.get_model(),
                    [
                        ModelRequest(parts=[SystemPromptPart(INSTRUCTIONS)]),
                        *history,
                        ModelRequest(parts=[UserPromptPart(question["prompt"])]),
                    ],
                    model_settings=factory.config_loader().request_settings(),
                )
                baseline_text = "".join(
                    part.content for part in baseline.parts if isinstance(part, TextPart)
                )
                row = service.submit(
                    conversation, "eval", "question", question["prompt"], definition
                )
                async with asyncio.timeout(180):
                    while row["status"] in {"queued", "running"}:
                        await asyncio.sleep(0.02)
                        row = store.get(row["id"], "eval")
                events = store.read_events(row["id"], "eval", limit=10000)
                with sessions() as db:
                    snapshots = [
                        dict(item)
                        for item in db.execute(
                            select(context_snapshots).where(context_snapshots.c.run_id == row["id"])
                        ).mappings()
                    ]
                answer = row["output"] or ""
                score = score_answer(answer, question)
                memory_checks = score_compaction(scenario, snapshots, events)
                results.append(
                    {
                        "prompt": question["prompt"],
                        "baseline_answer": baseline_text,
                        "compacted_answer": answer,
                        "baseline": score_answer(baseline_text, question),
                        "compacted": score,
                        "run_status": row["status"],
                        "error_code": row["error_code"],
                        "snapshots": snapshots,
                        "events": events,
                        "budget": row["budget"],
                        "memory_checks": memory_checks,
                        "compaction_executed": any(
                            e["kind"] == "context_compacted" for e in events
                        ),
                        "passed": row["status"] == "finished"
                        and memory_checks["passed"]
                        and score["passed"],
                    }
                )
        finally:
            await service.close()
            engine.dispose()
    return {
        "id": scenario["id"],
        "title": scenario["title"],
        "seeded_history_tokens_estimate": message_tokens(history),
        **score_scenario(results),
        "questions": results,
    }


async def async_main(args):
    scenarios = load_scenarios(Path(args.scenarios))
    selected = (
        scenarios
        if args.scenario == "all"
        else [item for item in scenarios if item["id"] == args.scenario]
    )
    if not selected:
        raise ValueError(f"unknown scenario: {args.scenario}")
    # Explicit stress configuration; reported, never hidden in the product.
    config = resolve_model_config().model_copy(
        update={
            "context_window_tokens": 8192,
            "context_compression_threshold_percent": 50,
            "max_output_tokens": 1024,
            "summary_output_tokens": 2048,
        }
    )
    factory = ModelFactory(lambda: config)
    try:
        results = [await run_scenario(item, factory) for item in selected]
    finally:
        await factory.close()
    report = {
        "suite": "native_context_compaction",
        "configuration": config.model_dump(mode="json"),
        "fixture": "seeded transcripts",
        "scenario_count": len(results),
        "passed": all(item["passed"] for item in results),
        "results": results,
        "product_acceptance_complete": False,
    }
    rendered = json.dumps(report, ensure_ascii=False, indent=2, default=str)
    if args.output:
        output = Path(args.output)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(rendered + "\n", encoding="utf-8")
        print(f"wrote {output}")
    else:
        print(rendered)
    return 0 if report["passed"] else 1


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scenario", default="all")
    parser.add_argument("--scenarios", default=str(SCENARIOS_PATH))
    parser.add_argument("--output")
    return asyncio.run(async_main(parser.parse_args()))


if __name__ == "__main__":
    raise SystemExit(main())
