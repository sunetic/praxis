@pytest.mark.skipif(not _llm_configured, reason="requires LLM API key")
def test_function_build_end_to_end_scheduler_history_cleanup(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    monkeypatch.setattr(functions_api, "WorkspaceStore", _SchedulerHistoryCleanupWorkspaceStore)
    session_factory, engine = _session_factory(tmp_path)
    db = session_factory()
    try:
        target_schedule = models.Schedule(
            name="history-target",
            status="active",
            target_type="function",
            target_id=999,
            schedule_type="interval",
            interval_seconds=3600,
            timezone="UTC",
        )
        db.add(target_schedule)
        db.flush()
        stale_run = models.ScheduleRun(
            schedule_id=target_schedule.id,
            run_id="target-stale",
            status="success",
            trigger_type="scheduled",
            attempt=1,
            retry_count=0,
            max_retries=0,
            created_at=datetime.utcnow() - timedelta(days=45),
        )
        fresh_run = models.ScheduleRun(
            schedule_id=target_schedule.id,
            run_id="target-fresh",
            status="success",
            trigger_type="scheduled",
            attempt=1,
            retry_count=0,
            max_retries=0,
            created_at=datetime.utcnow() - timedelta(days=5),
        )
        db.add_all([stale_run, fresh_run])
        db.commit()

        function = functions_api.create_function({"name": "调度历史清理"}, db=db)
        built = functions_api.build_function(
            function["id"],
            {"prompt": "构建一个 Function，清理 30 天前的 Scheduler 运行历史，先 dry-run 验证"},
            db=db,
        )
        assert built["build_run"]["status"] == "done"
        assert "scheduler_history.delete" in str(built["function"]["draft_code"] or "")

        draft_run = asyncio.run(
            functions_api.invoke_function(
                function["id"],
                {
                    "payload": {
                        "target_schedule_id": target_schedule.id,
                        "retention_seconds": 30 * 24 * 3600,
                        "dry_run": True,
                    },
                    "runtime_path": "draft",
                    "execution_mode": "plan",
                    "write_mode": "readonly",
                },
                db=db,
            )
        )
        assert draft_run["status"] == "success"
        assert draft_run["output"]["dry_run"] is True
        assert draft_run["output"]["candidate_count"] == 1

        unchanged_run_ids = {
            row.run_id
            for row in db.query(models.ScheduleRun)
            .filter(models.ScheduleRun.schedule_id == target_schedule.id)
            .all()
        }
        assert "target-stale" in unchanged_run_ids
        assert "target-fresh" in unchanged_run_ids

        released = functions_api.release_function(function["id"], {}, db=db)
        assert released["function"]["status"] == "released"

        cleanup_schedule = schedules_api.create_schedule(
            {
                "name": "cleanup-history-daily",
                "function_id": function["id"],
                "schedule_type": "interval",
                "interval_seconds": 86400,
                "input_payload": {
                    "target_schedule_id": target_schedule.id,
                    "retention_seconds": 30 * 24 * 3600,
                    "dry_run": False,
                },
            },
            db=db,
        )
        run_now = asyncio.run(schedules_api.run_schedule_now(cleanup_schedule["id"], db=db))
        assert isinstance(run_now["run_id"], str)

        target_run_ids_after = {
            row.run_id
            for row in db.query(models.ScheduleRun)
            .filter(models.ScheduleRun.schedule_id == target_schedule.id)
            .all()
        }
        assert "target-stale" not in target_run_ids_after
        assert "target-fresh" in target_run_ids_after

        cleanup_runs = schedules_api.list_schedule_runs(cleanup_schedule["id"], db=db)
        assert cleanup_runs
        latest_cleanup = cleanup_runs[0]
        assert latest_cleanup["status"] == "success"
        output_payload = latest_cleanup.get("output_payload") if isinstance(latest_cleanup.get("output_payload"), dict) else {}
        assert output_payload.get("deleted_count") == 1
    finally:
        db.close()
        engine.dispose()


