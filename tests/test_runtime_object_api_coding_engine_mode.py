def test_agent_runtime_kernel_handles_complex_task_catalog():
    class _StubReflectionPlanner:
        def decide(
            self,
            *,
            scope: str,
            initial_goal: str,
            current_goal: str,
            attempt_index: int,
            max_attempts: int,
            diagnostics: list[str],
            error: str,
            attempts: list[BuildAttempt],
        ) -> ReflectionDecision:
            _ = scope, current_goal, diagnostics, error, attempts
            if attempt_index >= max_attempts:
                return ReflectionDecision(action="needs_clarification", reason="max_attempts_exhausted")
            return ReflectionDecision(
                action="retry",
                reason="stub_retry",
                next_goal=f"{initial_goal}\nRetry attempt {attempt_index + 1}: 调整数据源并重试",
                missing=[],
            )

    scenarios = [
        "统计信息采集健康总览：按集群/租户筛选，展示趋势与问题表",
        "慢 SQL 治理：按实例筛选，展示 TopN 与 P95 趋势",
        "备份可用性巡检：展示成功率、失败分布与高风险租户",
    ]

    for scenario in scenarios:
        counter = {"value": 0}
        kernel = BuildVerifyLoop(max_attempts=3, reflection_planner=_StubReflectionPlanner())

        def _verify(build_result: Any, goal: str, attempt_index: int, attempts: list[BuildAttempt]) -> VerificationOutcome:
            _ = build_result, goal, attempt_index, attempts
            counter["value"] += 1
            passed = counter["value"] >= 2
            return VerificationOutcome(
                passed=passed,
                diagnostics=[] if passed else ["schema_mismatch", "field_missing"],
                payload={"passed": passed},
                summary="ok" if passed else "retry",
            )

        result = kernel.run(
            scope="function.build",
            initial_goal=scenario,
            build_step=lambda goal, attempt_index, attempts: {"attempt": attempt_index, "goal": goal},
            verify_step=_verify,
        )
        assert result.status == "done"
        assert len(result.attempts) >= 2


